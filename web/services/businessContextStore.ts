const BUSINESS_CONTEXT_STORAGE_KEY = "flowfit-business-context-events";

function nowIso() {
  return new Date().toISOString();
}

function readJson<T>(key: string, fallback: T): T {
  if (typeof window === "undefined") return fallback;

  try {
    const raw = window.localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}

function writeJson<T>(key: string, value: T) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(key, JSON.stringify(value));
}

function buildEventFromForm(intake: RawFieldIntake, form: AutoGeneratedIntakeForm): BusinessContextEvent {
  const now = nowIso();
  return {
    id: makeFlowFitId("business-event"),
    companyId: intake.companyId,
    eventType: mapDetectedTypeToBusinessEvent(form.detectedType),
    title: form.title,
    summary: form.aiSummary,
    source: "field_intake",
    sourceId: intake.id,
    confidence: calculateFormConfidence(form.fields),
    verificationStatus: form.missingFields.length ? "needs_more_info" : "unverified",
    extractedFacts: form.fields.map((field) => ({
      key: field.label,
      value: String(field.value ?? "확인 필요"),
      confidence: field.confidence,
      sourceText: intake.rawText,
    })),
    usableForAiPlanning: true,
    usableForExternalAction: false,
    createdAt: now,
    updatedAt: now,
  };
}

