export function getBusinessContextEvents() {
  return readJson(BUSINESS_CONTEXT_STORAGE_KEY, initialBusinessContextEvents);
}

export function saveBusinessContextEvents(events: BusinessContextEvent[]) {
  writeJson(BUSINESS_CONTEXT_STORAGE_KEY, events);
}

export function createBusinessContextEvent(intake: RawFieldIntake, form: AutoGeneratedIntakeForm) {
  const event = buildEventFromForm(intake, form);
  saveBusinessContextEvents([event, ...getBusinessContextEvents()]);
  return event;
}

export function updateBusinessContextEvent(
  eventId: string,
  updater: (event: BusinessContextEvent) => BusinessContextEvent,
) {
  const nextEvents = getBusinessContextEvents().map((event) => (event.id === eventId ? updater(event) : event));
  saveBusinessContextEvents(nextEvents);
  return nextEvents;
}

export function setBusinessContextVerificationStatus(eventId: string, verificationStatus: VerificationStatus) {
  return updateBusinessContextEvent(eventId, (event) => ({
    ...event,
    verificationStatus,
    updatedAt: nowIso(),
  }));
}
