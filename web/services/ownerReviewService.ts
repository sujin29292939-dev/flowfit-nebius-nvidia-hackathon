  const now = nowIso();
  const workType =
    record.recordType === "customer_complaint"
      ? "customer_reply"
      : record.recordType === "payment_candidate"
        ? "staff_confirmation"
        : "order_check";

  const resultTitle =
    record.recordType === "customer_complaint"
      ? "고객 응대 초안 생성"
      : record.recordType === "payment_candidate"
        ? "회계 확인 요청"
        : "후속 확인 작업";

  const resultContent =
    record.recordType === "payment_candidate"
