function nowIso() {
  return new Date().toISOString();
}

function mapRecordType(event: BusinessContextEvent): OfficialRecordType {
  switch (event.eventType) {
    case "field_order_candidate":
      return "order_candidate";
    case "purchase_order_candidate":
      return "order_candidate";
    case "quote_request_candidate":
      return "quote_request";
    case "payment_report_candidate":
    case "receipt_candidate":
      return "payment_candidate";
    case "customer_complaint_candidate":
      return "customer_complaint";
    case "inventory_issue_candidate":
      return "inventory_issue";
    case "delivery_change_candidate":
      return "delivery_change";
    case "contract_candidate":
      return "contract_candidate";
    default:
      return "task";
  }
}

function getRiskLevel(recordType: OfficialRecordType): RiskLevel {
  if (recordType === "payment_candidate" || recordType === "contract_candidate") return "high";
  if (recordType === "customer_complaint") return "medium";
  if (recordType === "order_candidate" || recordType === "delivery_change") return "medium";
  return "low";
}

function getRecordStatus(recordType: OfficialRecordType): OfficialRecordStatus {
  if (recordType === "payment_candidate" || recordType === "contract_candidate") {
    return "pending_secondary_review";
  }

  return "active";
}

function canUseForExternalAction(recordType: OfficialRecordType, riskLevel: RiskLevel) {
  if (riskLevel === "high") return false;
  return recordType === "order_candidate" || recordType === "delivery_change";
}

function buildStructuredData(form: AutoGeneratedIntakeForm, correctedData?: Record<string, string | number | boolean | null>) {
  const extracted = form.fields.reduce<Record<string, string | number | boolean | null>>((acc, field) => {
    acc[field.label] = field.value ?? null;
    return acc;
  }, {});

  return {
    ...extracted,
    ...(correctedData ?? {}),
  };
}

