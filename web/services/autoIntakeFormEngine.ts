const AUTO_INTAKE_FORM_STORAGE_KEY = "flowfit-auto-intake-forms";

function nowIso() {
  return new Date().toISOString();
}

function readJson<T>(key: string, fallback: T): T {
  if (typeof window === "undefined") return fallback;

  try {
    const raw = window.localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}

function writeJson<T>(key: string, value: T) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(key, JSON.stringify(value));
}

function makeQuestion(missingField: string) {
  if (missingField === "상품명") {
    return {
      question: "상품명이 기존 납품 상품과 동일한가요?",
      options: ["기존 상품과 동일", "사진에 있음", "직접 입력 필요", "잘 모르겠음"],
    };
  }

  if (missingField === "주문번호") {
    return {
      question: "고객 주문번호를 확인할 수 있나요?",
      options: ["주문번호 확인됨", "고객에게 확인 필요", "담당자 확인 중"],
    };
  }

  return {
    question: `${missingField} 정보를 확인해주세요.`,
    options: ["확인됨", "확인 중", "잘 모르겠음"],
  };
}

export function buildAutoGeneratedForm(intake: RawFieldIntake): AutoGeneratedIntakeForm {
  const now = nowIso();
  const detectedType = detectIntakeType(intake);
  const fields = extractFieldsFromIntake(intake, detectedType);
  const missingFields = findMissingFields(fields);
  const typeLabel = getDetectedTypeLabel(detectedType);
  const firstPartner = fields.find((item) => item.label.includes("거래처"))?.value;
  const title =
    detectedType === "purchase_order_document" && firstPartner
      ? `${firstPartner} 추가 주문 후보`
      : `${typeLabel} 판별 결과`;

  return {
    id: makeFlowFitId("auto-form"),
    companyId: intake.companyId,
    intakeId: intake.id,
    title,
    detectedType,
    rawInputSummary: intake.rawText || "첨부 자료 중심의 현장 접수입니다.",
    fields,
    missingFields,
    suggestedQuestions: missingFields.map((missingField) => ({
      id: makeFlowFitId("question"),
      ...makeQuestion(missingField),
    })),
    aiSummary: `${typeLabel}로 보이는 현장 접수입니다. 평균 신뢰도 ${Math.round(
      calculateFormConfidence(fields) * 100,
    )}%이며, 대표 확인 전에는 공식 처리에 사용할 수 없습니다.`,
    aiWarnings: missingFields.length
      ? [`부족 정보: ${missingFields.join(", ")}`, "대표 승인 전 외부 발송과 정식 처리에는 사용할 수 없습니다."]
      : ["대표 승인 전 외부 발송과 정식 처리에는 사용할 수 없습니다."],
    status: "ready_for_owner_review",
    createdAt: now,
    updatedAt: now,
  };
}

