export function getAutoGeneratedIntakeForms() {
  return readJson(AUTO_INTAKE_FORM_STORAGE_KEY, initialAutoGeneratedIntakeForms);
}

export function saveAutoGeneratedIntakeForms(forms: AutoGeneratedIntakeForm[]) {
  writeJson(AUTO_INTAKE_FORM_STORAGE_KEY, forms);
}

export function createAutoGeneratedIntakeForm(intake: RawFieldIntake) {
  const form = buildAutoGeneratedForm(intake);
  saveAutoGeneratedIntakeForms([form, ...getAutoGeneratedIntakeForms()]);
  return form;
}

export function updateAutoGeneratedIntakeForm(
  formId: string,
  updater: (form: AutoGeneratedIntakeForm) => AutoGeneratedIntakeForm,
) {
  const nextForms = getAutoGeneratedIntakeForms().map((form) => (form.id === formId ? updater(form) : form));
  saveAutoGeneratedIntakeForms(nextForms);
  return nextForms;
}

export function setAutoGeneratedFormStatus(formId: string, status: AutoGeneratedIntakeFormStatus) {
  return updateAutoGeneratedIntakeForm(formId, (form) => ({
    ...form,
    status,
    updatedAt: nowIso(),
  }));
}
