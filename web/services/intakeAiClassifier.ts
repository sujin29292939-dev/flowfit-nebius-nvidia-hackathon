import { makeFlowFitId } from "@/services/fieldIntakeStore";
import type {
  AutoGeneratedField,
  BusinessEventType,
  DetectedIntakeType,
  RawFieldIntake,
} from "@/types/flowfit";

function includesAny(text: string, words: string[]) {
  return words.some((word) => text.includes(word));
}

export function detectIntakeType(intake: RawFieldIntake): DetectedIntakeType {
  const text = intake.rawText ?? "";

  if (includesAny(text, ["영수증", "입금", "송금"])) return "receipt_document";
  if (includesAny(text, ["화냄", "클레임", "불만", "배송 늦"])) return "customer_complaint";
  if (includesAny(text, ["계약", "구두"])) return "verbal_contract";
  if (includesAny(text, ["재고", "파손", "부족"])) return "inventory_issue";
  if (includesAny(text, ["견적", "견적서"])) return "quote_request";
  if (includesAny(text, ["배송 변경", "주소 변경", "납기 변경"])) return "delivery_change";
  if (includesAny(text, ["발주", "주문", "박스", "추가"])) return "purchase_order_document";
  if (intake.imageUrls.length) return "handwritten_memo";
  return "other";
}

export function mapDetectedTypeToBusinessEvent(type: DetectedIntakeType): BusinessEventType {
  switch (type) {
    case "field_order":
    case "phone_order":
      return "field_order_candidate";
    case "purchase_order_document":
      return "purchase_order_candidate";
    case "quote_request":
      return "quote_request_candidate";
    case "payment_report":
      return "payment_report_candidate";
    case "receipt_document":
      return "receipt_candidate";
    case "customer_complaint":
      return "customer_complaint_candidate";
    case "inventory_issue":
      return "inventory_issue_candidate";
    case "delivery_change":
      return "delivery_change_candidate";
    case "verbal_contract":
      return "contract_candidate";
    default:
      return "field_order_candidate";
  }
}

